// Original mapper-0 program: once per frame it samples both A buttons into $20/$21, counts held
// frames in $22 (player 1) and $23 (player 2) and paints the backdrop with ($21 + $22 + $23) & $3f.
module.exports = function nesFixture() {
  const rom = Buffer.alloc(16 + 16384 + 8192);
  rom.set([0x4e, 0x45, 0x53, 0x1a, 1, 1]);
  const code = [0x78, 0xd8, 0xa2, 0xff, 0x9a, 0xe8, 0x8e, 0, 0x20, 0x8e, 1, 0x20, 0x86, 0x22, 0x86, 0x23,
    0xad, 2, 0x20, 0x10, 0xfb, 0xa9, 0x3f, 0x8d, 6, 0x20, 0xa9, 0, 0x8d, 6, 0x20,
    0xa9, 0x21, 0x8d, 7, 0x20, 0xa9, 0x0a, 0x8d, 1, 0x20];
  const loopAddress = 0x8000 + code.length;
  code.push(0xad, 2, 0x20, 0x10, 0xfb,
    0xa9, 1, 0x8d, 0x16, 0x40, 0xa9, 0, 0x8d, 0x16, 0x40,
    0xad, 0x16, 0x40, 0x29, 1, 0x85, 0x20, 0xf0, 2, 0xe6, 0x22,
    0xad, 0x17, 0x40, 0x29, 1, 0x85, 0x21, 0xf0, 2, 0xe6, 0x23,
    0xa9, 0x3f, 0x8d, 6, 0x20, 0xa9, 0, 0x8d, 6, 0x20,
    0xa5, 0x22, 0x18, 0x65, 0x23, 0x18, 0x69, 0x21, 0x29, 0x3f, 0x8d, 7, 0x20,
    0xa9, 0, 0x8d, 6, 0x20, 0x8d, 6, 0x20,
    0x4c, loopAddress & 255, loopAddress >> 8);
  rom.set(code, 16);
  for (const vector of [0x3ffa, 0x3ffc, 0x3ffe]) rom.writeUInt16LE(0x8000, 16 + vector);
  return rom;
};
